using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Dynamics.Constraint.Components;
using VRC.SDKBase;

/// <summary>Builds the two FX controllers that Modular Avatar merges into the avatar.</summary>
public static class TranslatorAnimationBuilder
{
    public const string ToggleControllerName = "Translator_Toggle.controller";
    public const string KatControllerName = "Translator_KAT.controller";
    public const string ToggleLayerName = "Translator_Toggle";

    /// <summary>
    /// Off / Appear / On layer on <see cref="TranslatorConfig.ActiveParam"/>. Paths are relative to the prefab root.
    /// Appear shows the pet and the sign, turns KAT on and clears it, and briefly snaps the pet to its place;
    /// On then lets it follow slowly. CatchUp snaps it over while its contact says it is far behind (a teleport).
    /// Off hides everything and clears the text.
    /// </summary>
    public static AnimatorController BuildToggleController(string outputDir)
    {
        var controller = NewController(outputDir + "/" + ToggleControllerName);
        controller.AddParameter(TranslatorConfig.ActiveParam, AnimatorControllerParameterType.Bool);
        controller.AddParameter(TranslatorConfig.KatVisibleParam, AnimatorControllerParameterType.Bool);
        controller.AddParameter(TranslatorConfig.KatPointerParam, AnimatorControllerParameterType.Int);
        controller.AddParameter(TranslatorConfig.NearParam, AnimatorControllerParameterType.Bool);

        var layer = controller.layers[0];
        layer.name = ToggleLayerName;
        layer.defaultWeight = 1f;
        controller.layers = new[] { layer };
        var sm = layer.stateMachine;

        var off = sm.AddState("Off", new Vector3(300, 100));
        var appear = sm.AddState("Appear", new Vector3(300, 200));
        var on = sm.AddState("On", new Vector3(300, 300));
        var catchUp = sm.AddState("CatchUp", new Vector3(550, 300));
        sm.defaultState = off;
        off.motion = SaveClip(ActiveClip(0f, null, 1f / 60f), outputDir + "/Translator_Off.anim");
        appear.motion = SaveClip(ActiveClip(1f, TranslatorConfig.AppearWeight, TranslatorConfig.AppearSeconds),
            outputDir + "/Translator_Appear.anim");
        on.motion = SaveClip(ActiveClip(1f, TranslatorConfig.FollowWeight, 1f / 60f), outputDir + "/Translator_On.anim");
        catchUp.motion = SaveClip(ActiveClip(1f, TranslatorConfig.AppearWeight, 1f / 60f), outputDir + "/Translator_CatchUp.anim");
        foreach (var s in new[] { off, appear, on, catchUp }) s.writeDefaultValues = false;

        // Clear on both edges: text sent while the toggle was off must not reappear when it is turned on.
        AddDriver(appear, (TranslatorConfig.KatVisibleParam, 1f),
            (TranslatorConfig.KatPointerParam, TranslatorConfig.KatClearPointer));
        AddDriver(off, (TranslatorConfig.KatVisibleParam, 0f),
            (TranslatorConfig.KatPointerParam, TranslatorConfig.KatClearPointer));

        Connect(off, appear, AnimatorConditionMode.If);
        Connect(appear, off, AnimatorConditionMode.IfNot);
        Connect(on, off, AnimatorConditionMode.IfNot);
        Connect(on, catchUp, AnimatorConditionMode.IfNot, TranslatorConfig.NearParam);
        Connect(catchUp, on, AnimatorConditionMode.If, TranslatorConfig.NearParam);
        Connect(catchUp, off, AnimatorConditionMode.IfNot);
        var settle = appear.AddTransition(on);
        settle.hasExitTime = true;
        settle.exitTime = 1f;
        settle.duration = 0f;
        EditorUtility.SetDirty(controller);
        return controller;
    }

    /// <summary>
    /// KAT's own text layers (no keyboard), generated by KAT's installer into an empty controller.
    /// KAT's clips animate "KillFrenzyAvatarText/Constraint/Text", so the controller is merged on Pet_Text.
    /// </summary>
    public static AnimatorController BuildKatController(string outputDir, int syncCount)
    {
        if (!TranslatorConfig.KatSyncChoices.Contains(syncCount))
            throw new ArgumentException("KAT の同期設定は 4、8、16 のどれかにしてください: " + syncCount);

        var controller = NewController(outputDir + "/" + KatControllerName);
        controller.RemoveLayer(0);

        // KAT's scripts have no asmdef (they compile into Assembly-CSharp), so call them by reflection.
        var settingsType = KatType("KillFrenzy.AvatarTextTools.Settings.KatSettings");
        var installer = KatType("KillFrenzy.AvatarTextTools.Utility.KatAnimatorInstaller");
        const int vrchat = 0, attachNone = 0;
        var settings = Activator.CreateInstance(settingsType, vrchat, false, attachNone, syncCount);
        bool ok = (bool)installer.GetMethod("InstallToAnimator").Invoke(null, new[] { controller, settings });
        if (!ok) throw new InvalidOperationException("KAT のアニメーターを作れませんでした。KAT を入れ直してください。");

        EditorUtility.SetDirty(controller);
        return controller;
    }

    /// <summary>Finds a KAT type in any loaded assembly; null when KAT is not imported.</summary>
    public static Type FindKatType(string fullName) =>
        AppDomain.CurrentDomain.GetAssemblies().Select(a => a.GetType(fullName)).FirstOrDefault(t => t != null);

    static Type KatType(string fullName) =>
        FindKatType(fullName) ?? throw new InvalidOperationException(
            "KAT（KillFrenzy Avatar Text）が見つかりません。KAT の unitypackage をインポートしてください。");

    internal static AnimatorController NewController(string path)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        AssetDatabase.DeleteAsset(path);
        return AnimatorController.CreateAnimatorControllerAtPath(path);
    }

    /// <summary>Shows or hides the pet and the sign; with a weight, also sets how hard the pet pulls toward its place.</summary>
    static AnimationClip ActiveClip(float active, float? followWeight, float seconds)
    {
        var clip = new AnimationClip();
        foreach (var path in new[] { TranslatorConfig.PetRootName, TranslatorConfig.SignRootName, TranslatorConfig.GazeName })
        {
            float value = path == TranslatorConfig.SignRootName && !TranslatorConfig.ShowSign ? 0f : active;
            AnimationUtility.SetEditorCurve(clip,
                EditorCurveBinding.FloatCurve(path, typeof(GameObject), "m_IsActive"),
                AnimationCurve.Constant(0f, seconds, value));
        }
        if (followWeight.HasValue)
            AnimationUtility.SetEditorCurve(clip,
                EditorCurveBinding.FloatCurve(TranslatorConfig.PetRootName + "/" + TranslatorConfig.PetFollowName,
                    typeof(VRCParentConstraint), TranslatorConfig.FollowWeightProperty),
                AnimationCurve.Constant(0f, seconds, followWeight.Value));
        return clip;
    }

    internal static AnimationClip SaveClip(AnimationClip clip, string path)
    {
        AssetDatabase.DeleteAsset(path);
        AssetDatabase.CreateAsset(clip, path);
        return clip;
    }

    static void AddDriver(AnimatorState state, params (string name, float value)[] sets)
    {
        var driver = state.AddStateMachineBehaviour<VRCAvatarParameterDriver>();
        driver.localOnly = true;
        driver.parameters = sets.Select(s => new VRC_AvatarParameterDriver.Parameter
        {
            type = VRC_AvatarParameterDriver.ChangeType.Set,
            name = s.name,
            value = s.value,
        }).ToList();
    }

    static void Connect(AnimatorState from, AnimatorState to, AnimatorConditionMode mode,
        string parameter = TranslatorConfig.ActiveParam)
    {
        var t = from.AddTransition(to);
        t.hasExitTime = false;
        t.duration = 0f;
        t.AddCondition(mode, 0f, parameter);
    }
}
