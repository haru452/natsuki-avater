"""Writes Assets/natsuki_veer02/Translator/KATChatBubble.shader: KillFrenzy Avatar Text (MIT) turned into a chat
bubble that always faces the viewer. The character properties and their buffer are copied from KAT's shader so
KAT's animations drive it unchanged; the drawing is new. Run from the project root:
python Tools/translator/chat_bubble_shader.py"""
import re

KAT = "Assets/KillFrenzy/AvatarText/Shaders/KF_AvatarTextShader.shader"
OUT = "Assets/natsuki_veer02/Translator/KATChatBubble.shader"

src = open(KAT, encoding="utf-8").read()
char_props = "\n".join(l for l in src.splitlines() if re.match(r"\s*_Char\d+\(", l))
cbuffer = src[src.index("CBUFFER_START(CharacterBuffer)"):src.index("CBUFFER_END") + len("CBUFFER_END")]
sum_fn = src[src.index("float sumCharacters()"):]
sum_fn = sum_fn[:sum_fn.index("}") + 1]

shader = r'''// Generated by Tools/translator/chat_bubble_shader.py from KillFrenzy Avatar Text (MIT, Copyright 2023 KillFrenzy /
// Evan Tran): the pet's subtitle as a chat bubble. White letters on a dark rounded bubble that always faces the
// viewer and shrinks to the text (one short line gets a small bubble; no text, no bubble). The bubble's bottom
// centre sits at the object's origin. Characters come from _Char0.._Char127, written by KAT's animations.
Shader "Translator/KATChatBubble"
{
    Properties
    {
        _MainTex("Texture", 2D) = "white" {}
        _MainColor("Text Colour", Color) = (0.93, 0.94, 0.97, 1)
        _BubbleColor("Bubble Colour", Color) = (0.063, 0.102, 0.18, 0.9)
        _TileX("Text Tile Count X", Float) = 16
        _TileY("Text Tile Count Y", Float) = 6
        _RowLength("Text Output Row Length", Float) = 32
        _RowColumns("Text Output Row Columns", Float) = 4
        [Toggle]_GrowEnabled("Grow Text with Distance", Range(0, 1)) = 1
        _PadX("Side Padding (cells)", Float) = 1.2
        _PadY("Top/Bottom Padding (rows)", Float) = 0.45
__CHAR_PROPS__
    }
    SubShader
    {
        Tags { "Queue" = "Transparent+10" "RenderType" = "Transparent" "IgnoreProjector" = "True" "DisableBatching" = "True" "PreviewType" = "Plane" }
        Cull Off
        ZWrite Off
        Blend SrcAlpha OneMinusSrcAlpha

        Pass
        {
            CGPROGRAM
            #pragma vertex vert
            #pragma fragment frag
            #pragma multi_compile_instancing
            #include "UnityCG.cginc"

            sampler2D _MainTex;
            float4 _MainTex_TexelSize;
            float4 _MainColor, _BubbleColor;
            float _TileX, _TileY, _RowLength, _RowColumns, _PadX, _PadY;
            float _GrowEnabled;

            __CBUFFER__

            __SUM__

            float charAt(float i) { return round(_Chars[clamp(i, 0, 127)]); }

            struct appdata
            {
                float4 vertex : POSITION;
                float2 uv : TEXCOORD0;
                UNITY_VERTEX_INPUT_INSTANCE_ID
            };

            struct v2f
            {
                float4 pos : SV_POSITION;
                float2 cell : TEXCOORD0;   // position in character cells: x from the left, y in rows from the top
                float4 box : TEXCOORD1;    // bubble in cells: xy = size, z = row height / cell width
                UNITY_VERTEX_OUTPUT_STEREO
            };

            v2f vert(appdata v)
            {
                v2f o;
                UNITY_SETUP_INSTANCE_ID(v);
                UNITY_INITIALIZE_VERTEX_OUTPUT_STEREO(o);

                // How much text there is: rows down to the last non-space character, and on a single row its length.
                float last = -1;
                for (int i = 0; i < 128; i++) if (charAt(i) != 0) last = i;
                float rows = last < 0 ? 0 : floor(last / _RowLength) + 1;
                float cols = rows <= 1 ? last + 1 : _RowLength;

                // Bubble in cells, padding included; this corner of it from the quad's uv (0..1, y up).
                float2 size = float2(cols + 2 * _PadX, rows + 2 * _PadY);
                float2 corner = float2(v.uv.x, 1 - v.uv.y) * size;          // y down from the top of the bubble
                o.cell = corner - float2(_PadX, _PadY);

                // Metres per cell from the object's scale (the quad is a whole page: _RowLength x _RowColumns).
                float2 scale = float2(length(unity_ObjectToWorld._m00_m10_m20), length(unity_ObjectToWorld._m01_m11_m21));
                float2 cellSize = scale / float2(_RowLength, _RowColumns);
                o.box = float4(size, cellSize.y / cellSize.x, 0);
                float2 offset = float2(corner.x - size.x / 2, size.y - corner.y) * cellSize;   // bottom centre at the origin
                if (rows == 0) offset = 0;                                                   // nothing to say: nothing drawn

                float4 center = float4(UnityObjectToViewPos(float3(0, 0, 0)), 1);
                if (_GrowEnabled > 0.5)
                {
                    float3 eye = _WorldSpaceCameraPos;
                    #ifdef USING_STEREO_MATRICES
                    eye = 0.5 * (unity_StereoWorldSpaceCameraPos[0] + unity_StereoWorldSpaceCameraPos[1]);
                    #endif
                    offset *= 1 + smoothstep(0, 1, distance(eye, unity_ObjectToWorld._14_24_34) - 0.5);
                }
                o.pos = mul(UNITY_MATRIX_P, center + float4(offset, 0, 0));
                return o;
            }

            // Rounded box: < 0 inside. p and half-size in cells, scaled so cells are square-ish (rows are taller).
            float roundedBox(float2 p, float2 half, float r)
            {
                float2 q = abs(p) - half + r;
                return length(max(q, 0)) + min(max(q.x, q.y), 0) - r;
            }

            fixed4 frag(v2f i) : SV_Target
            {
                // Bubble, measured in cell widths (a row is taller than a cell is wide).
                float aspect = i.box.z;
                float2 p = (i.cell + float2(_PadX, _PadY) - i.box.xy / 2) * float2(1, aspect);
                float2 half = i.box.xy / 2 * float2(1, aspect);
                float d = roundedBox(p, half, min(half.y, 1.6));
                float bubble = saturate(0.5 - d / max(fwidth(d), 1e-4));
                if (bubble <= 0) discard;

                // The letter in this cell (KAT's tile sheet).
                float2 cellIdx = floor(i.cell);
                float4 col = _BubbleColor;
                if (all(i.cell >= 0) && i.cell.x < _RowLength && i.cell.y < _RowColumns)
                {
                    float c = charAt(cellIdx.x + cellIdx.y * _RowLength);
                    float limit = _TileX * _TileY;
                    c = min(c, limit);
                    if (c < 0) c += floor(c / limit) * limit;
                    float2 inCell = frac(i.cell);
                    float2 uv = float2(inCell.x, 1 - inCell.y) / float2(_TileX, _TileY)
                              + float2(fmod(c, _TileX) / _TileX, 1 - (floor(c / _TileX) + 1) / _TileY);
                    float a = tex2D(_MainTex, uv).a;
                    a = saturate((a - 0.5) / max(fwidth(a), 1e-3) + 0.5);
                    col.rgb = lerp(_BubbleColor.rgb, _MainColor.rgb, a);
                    col.a = lerp(_BubbleColor.a, 1, a);
                }
                col.a *= bubble;

                // Only to make Unity keep the _CharXX properties.
                [branch] if (col.a == 65536) return sumCharacters();
                return col;
            }
            ENDCG
        }
    }
}
'''
shader = (shader.replace("__CHAR_PROPS__", char_props)
          .replace("__CBUFFER__", cbuffer.replace("\n", "\n            "))
          .replace("__SUM__", sum_fn.replace("\n", "\n            ")))
open(OUT, "w", encoding="utf-8", newline="\n").write(shader)
print("wrote", OUT)
